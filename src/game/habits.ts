import { biomeStructures, STRUCTURE_NAME, type Structure } from "./spots.ts";

export type FightStyle = "runner" | "diver" | "jumper" | "bulldog" | "thrasher";

export type Habit = {
  /** Where it holds (1–3). */
  structures: Structure[];
  /** Preferred depth. */
  depth: Depth;
  /** Active windows. */
  feeds: Window[];
  /** Presentations it hits (2–3). */
  likes: LureFamily[];
  /** Retrieves it wants (1–2). */
  retrieve: Retrieve[];
  /** Weather ids (0 sunny, 1 rain, 2 storm, 3 fog, 4 night) it bites better in; [] = indifferent. */
  weather: number[];
  /** How it fights (WP-3 uses this). */
  fight: FightStyle;
  /** 0.6–1.8; scales the fight length. */
  stamina: number;
};

const FIGHT_BY_ARCH: Record<Arch, FightStyle> = {
  fish: "runner",
  eel: "thrasher",
  round: "bulldog",
  ray: "diver",
  shark: "runner",
  whale: "bulldog",
  turtle: "bulldog",
  squid: "diver",
  seahorse: "thrasher",
  angler: "diver",
  crab: "bulldog",
  jelly: "thrasher",
};

const STAMINA_BY_RARITY = [0.7, 0.9, 1.1, 1.4, 1.8];

/** The generated habit for slot `i` of water `b`. */
function ruleHabit(b: number, i: number): Habit {
  const name = BIOMES[b].fish[i];
  const t = rarityOf(i);
  const S = biomeStructures(b);
  const n = S.length;
  const structures: Structure[] = [S[(i * 7) % n]];
  const second = S[(i * 7 + 2) % n];
  if (second !== structures[0]) structures.push(second);
  /* Species i and i+12 would otherwise share a profile (4 and 3 both divide 12), so the
     rule is nudged by which dozen the slot is in. Twins make "the right rig" ambiguous. */
  const salt = Math.floor(i / 12);
  const feeds: Window[] = [WINDOWS[(i + salt) % 4]];
  if (t === 0 && !feeds.includes("day")) feeds.push("day");
  const likes: LureFamily[] = [
    FAMILIES[(i * 5 + salt * 3 + b) % 12],
    FAMILIES[(i * 5 + salt * 3 + b + 4) % 12],
  ];
  const third = FAMILIES[(i * 5 + salt * 3 + b + 8) % 12];
  if (t >= 2 && !likes.includes(third)) likes.push(third);
  const retrieve: Retrieve[] = [RETRIEVES[(i + salt) % 4]];
  if (i % 2 === 0) retrieve.push(RETRIEVES[(i + salt + 1) % 4]);
  return {
    structures,
    depth: ((i + salt) % 3) as Depth,
    feeds,
    likes,
    retrieve,
    weather: i % 3 === 0 ? [1 + (i % 4)] : [],
    fight: FIGHT_BY_ARCH[archetypeOf(name)],
    stamina: STAMINA_BY_RARITY[t],
  };
}

/* ── Hand-tuned real fish ─────────────────────────────────────────────────
   Keyed by species name, applied wherever that name appears. Structures that a
   particular water does not have are simply ignored there (Largemouth likes
   timber, but the Pond has none). */

function H(
  structures: Structure[],
  depth: Depth,
  feeds: Window[],
  likes: LureFamily[],
  retrieve: Retrieve[],
  weather: number[],
  fight: FightStyle,
  stamina: number,
): Habit {
  return { structures, depth, feeds, likes, retrieve, weather, fight, stamina };
}

