/* What every species does (docs/architecture/04 §3.2).

   375 habits are generated by RULE from the species' slot in its water, then the
   fish an angler actually knows are overridden by hand with real-world truth
   (the table at the bottom). `habitOf(b, i)` is the only way in. */

