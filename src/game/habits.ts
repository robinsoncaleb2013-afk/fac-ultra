export const REAL_FISH_COUNT = Object.keys(REAL_FISH).length;

let cache: Habit[][] | null = null;

function build(): Habit[][] {
  return BIOMES.map((biome, b) =>
    biome.fish.map((name, i) => {
      const real = REAL_FISH[name];
      return real
        ? {
            ...real,
            structures: [...real.structures],
            feeds: [...real.feeds],
            likes: [...real.likes],
            retrieve: [...real.retrieve],
            weather: [...real.weather],
          }
        : ruleHabit(b, i);
    }),
  );
}

export function habitOf(b: number, i: number): Habit {
  cache ??= build();
  return cache[b]?.[i] ?? cache[0][0];
}

/** Every habit in one water (index = species slot). */
export function habitsOfBiome(b: number): Habit[] {
  cache ??= build();
  return cache[b] ?? cache[0];
}

export function isRealFish(name: string): boolean {
  return name in REAL_FISH;
}

/* ── Words for the dex (plain English, short sentences) ───────────────── */

function joinList(items: string[], conj = "and"): string {
  if (items.length <= 1) return items[0] ?? "";
  if (items.length === 2) return `${items[0]} ${conj} ${items[1]}`;
  return `${items.slice(0, -1).join(", ")}, ${conj} ${items[items.length - 1]}`;
}

const FEED_PHRASE: Record<Window, string> = {
  dawn: "dawn",
  day: "the daytime",
  dusk: "dusk",
  night: "night",
};
const WEATHER_PHRASE = ["a sunny day", "the rain", "a storm", "fog", "night"];
const FIGHT_PHRASE: Record<FightStyle, string> = {
  runner: "It runs. Give it line when it takes off.",
  diver: "It dives deep and pulls steady. Be patient.",
  jumper: "It leaps out of the water. Ease off when it jumps.",
  bulldog: "It digs in and pulls hard. It tires out slowly.",
  thrasher: "It thrashes side to side. Keep a steady hand.",
};

/** "Likes plastic worms and topwater lures at dawn and dusk, around weeds and docks." */
export function habitLikes(h: Habit): string {
  const lures = joinList(h.likes.map((f) => FAMILY_INFO[f].plural));
  const when = joinList(h.feeds.map((w) => FEED_PHRASE[w]));
  const where = joinList(h.structures.map((s) => STRUCTURE_NAME[s].plural));
  return `Likes ${lures} at ${when}, around ${where}.`;
}

/** "Fish it deep and slow." */
export function habitHow(h: Habit): string {
  const how = joinList(
    h.retrieve.map((r) => RETRIEVE_INFO[r].adverb),
    "or",
  );
  return `Fish it ${DEPTH_INFO[h.depth].short}, with a ${how} retrieve.`;
}

export function habitWeather(h: Habit): string | null {
  if (!h.weather.length) return null;
  return `Bites best in ${joinList(
    h.weather.map((w) => WEATHER_PHRASE[w] ?? "any weather"),
    "or",
  )}.`;
}

export function habitFight(h: Habit): string {
  return FIGHT_PHRASE[h.fight];
}

/** The whole dex paragraph. */
export function habitSentences(h: Habit): string[] {
  const out = [habitLikes(h), habitHow(h)];
  const w = habitWeather(h);
  if (w) out.push(w);
  out.push(habitFight(h));
  return out;
}
