#!/usr/bin/env node
/**
 * Stamp a new "build epoch" into src/lib/build-epoch.generated.ts so every build is different.
 * Part of `npm run build` (test-phase auto-reset, docs/TEST-PHASE.md).
 *
 *   node scripts/build-epoch.mjs          stamp a new epoch (run before the bundler)
 *   node scripts/build-epoch.mjs restore  put "dev" back (run after the bundler)
 *
 * The epoch is `<commit>-<UTC build time>` (commit from VERCEL_GIT_COMMIT_SHA / GITHUB_SHA / FAC_COMMIT when
 * present, otherwise just the time). FAC_TEST_RESET_EPOCH forces an exact value. FAC_TEST_RESET (0 or 1) is
 * recorded too, so a build made with the switch off stays off in the browser.
 * Like scripts/copy-pglite-assets.mjs this never touches vite.config.ts, the Dockerfile or the CI files.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** @param {Record<string, string | undefined>} env @param {Date} now */
export function computeEpoch(env, now = new Date()) {
  const forced = (env.FAC_TEST_RESET_EPOCH ?? "").trim();
  if (forced) return forced.replace(/[^\w.-]/g, "").slice(0, 64) || "forced";
  const t = now.toISOString().replace(/[-:T]/g, "").slice(0, 14); // 20261102183045
  const sha = (env.VERCEL_GIT_COMMIT_SHA || env.GITHUB_SHA || env.FAC_COMMIT || "").trim().slice(0, 7);
  return sha ? `${sha.replace(/[^\w]/g, "")}-${t}` : t;
}

/** @param {string | undefined} v @returns {boolean | null} */
export function switchOf(v) {
  const t = (v ?? "").trim().toLowerCase();
  if (["0", "false", "off", "no"].includes(t)) return false;
  if (["1", "true", "on", "yes"].includes(t)) return true;
  return null;
}

/** The file text for a given epoch and switch. @param {string} epoch @param {boolean | null} on */
export function render(epoch, on) {
  return `/* GENERATED by scripts/build-epoch.mjs during \`npm run build\` (it stamps a new value on every build and
   puts "dev" back when the build ends). Do not edit by hand; do not commit a stamped value.
   "dev" means "not a stamped build": dev servers and unit tests use it so nothing wipes on a hot reload. */
export const BUILD_EPOCH: string = ${JSON.stringify(epoch)};
/** The switch as it stood when the build ran (FAC_TEST_RESET at build time), or null when it was not set. */
export const BUILD_SWITCH: boolean | null = ${on === null ? "null" : String(on)};
`;
}

const FILE = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "build-epoch.generated.ts");

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv[2] === "restore") {
    writeFileSync(FILE, render("dev", null));
    console.log("[build-epoch] restored the development value");
  } else {
    const epoch = computeEpoch(process.env);
    const on = switchOf(process.env.FAC_TEST_RESET);
    writeFileSync(FILE, render(epoch, on));
    console.log(`[build-epoch] this build is ${epoch}${on === null ? "" : `, reset switch ${on ? "ON" : "OFF"}`}`);
  }
}
